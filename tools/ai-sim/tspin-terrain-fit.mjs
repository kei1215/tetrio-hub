// Learn the vA T-Spin terrain table from replay pieces (tspin-terrain-data.mjs output).
// Label of a board (after a lock): the same player fires a TSD / TST within the next K pieces.
// Model: p = sigmoid(a + LSE_x(w[key_x]) - log 8) over the planner's tShapeKeys (shared weights).
// Run: node tspin-terrain-fit.mjs <out ai-tshape-table.js> <train.jsonl,...> [--test file.jsonl] [K=6]
import fs from "node:fs";
import { createRequire } from "node:module";
const SP = createRequire(import.meta.url)("../patch/ai-src/engine/ai-spin-planner.js");
const args = process.argv.slice(2);
const out = args[0], trainFiles = args[1].split(","), ti = args.indexOf("--test"), testFile = ti > 0 ? args[ti + 1] : null;
const K = Number(process.env.K || 6);
function load(f) {
  const L = fs.readFileSync(f, "utf8").trim().split("\n").map(JSON.parse), data = [];
  for (let i = 0; i < L.length; i++) {
    let y = 0;
    for (let j = i + 1; j <= i + K && j < L.length; j++) { const l = L[j]; if (l.file !== L[i].file || l.round !== L[i].round || l.who !== L[i].who) break; if (l.mino === "t" && l.spin === "normal" && l.lines >= 2 && l.lines <= 3) { y = 1; break; } }
    if (L[i].lines > 4) continue; // desynced replay pieces
    data.push({ keys: SP.tShapeKeys(L[i].rows), y });
  }
  return data;
}
const train = trainFiles.flatMap(load), test = testFile ? load(testFile) : [];
const w = new Map(); let a = 0;
const score = (d) => { let m = -Infinity; const v = d.keys.map((k) => w.get(k) || 0); for (const x of v) if (x > m) m = x; let z = 0; for (const x of v) z += Math.exp(x - m); return { v, m, z, s: m + Math.log(z) - Math.log(d.keys.length) }; };
const l2 = Number(process.env.L2 || 0.02), lr = 0.1;
for (let ep = 0; ep < 12; ep++) {
  for (const d of train) {
    const { v, m, z, s } = score(d), p = 1 / (1 + Math.exp(-(a + s))), g = d.y - p;
    a += lr * 0.1 * g;
    d.keys.forEach((k, i) => { const sw = Math.exp(v[i] - m) / z, old = w.get(k) || 0; w.set(k, old + lr * (g * sw - l2 * old)); });
  }
}
function auc(set) {
  const sc = set.map((d) => [score(d).s, d.y]).sort((x, y) => x[0] - y[0]);
  let pos = 0, neg = 0, sum = 0; for (const [, y] of sc) { if (y) { pos++; sum += neg; } else neg++; }
  return +(sum / Math.max(1, pos * neg)).toFixed(3);
}
const pr = (set) => +(set.reduce((s, d) => s + d.y, 0) / Math.max(1, set.length)).toFixed(3);
console.log(JSON.stringify({ train: train.length, test: test.length, posRate: [pr(train), pr(test)], aucTrain: auc(train), aucTest: test.length ? auc(test) : null, keys: w.size }));
const table = {}; for (const [k, v] of w) if (Math.abs(v) >= 0.02) table[k] = +v.toFixed(3);
fs.writeFileSync(out, `/* vA T-Spin terrain table: learned from real TL replays (user y_kei1215 + 5han), label =
   TSD / TST within ${K} pieces. Generated by tools/ai-sim/tspin-terrain-fit.mjs; do not edit. */
(function(root){root.LocalTShapeTable=${JSON.stringify(table)};})(typeof window==='undefined'?globalThis:window);
`);
console.log("wrote", out, Object.keys(table).length, "keys");
